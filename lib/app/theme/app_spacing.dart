/// The spacing scale: the only sizes used for padding and gaps.
///
/// Using these names instead of raw numbers keeps spacing consistent across
/// screens, and lets us adjust the whole app's rhythm in one place.
abstract final class AppSpacing {
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
}
